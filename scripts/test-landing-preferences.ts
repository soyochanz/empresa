const now = Date.now();
const valid = { version: 1, analytics: true, savedAt: now, expiresAt: now + CONSENT_DAYS * 86400000 };
assert.equal(parseConsent('broken'), null);
assert.equal(parseConsent(JSON.stringify({...valid,version:2})), null);
assert.equal(parseConsent(JSON.stringify({...valid,expiresAt:now-1})), null);
assert.equal(parseConsent(JSON.stringify({...valid,analytics:'true'})), null);
assert.equal(parseConsent(JSON.stringify(valid))?.analytics, true);
const storage = () => {
 const values = new Map<string,string>();
 return {getItem:(key:string)=>values.get(key)||null,setItem:(key:string,value:string)=>values.set(key,value),removeItem:(key:string)=>values.delete(key)};
};
const local = storage(), session = storage();
Object.assign(globalThis,{window:{location:{hostname:'example.com',href:'https://example.com/es',pathname:'/es'},localStorage:local,sessionStorage:session},document:{referrer:''}});
let calls = 0;
Object.assign(globalThis,{fetch:async (_url:string,options:any)=>{calls++; assert.equal(options.headers['X-Althera-Consent'],'analytics-v1');return {};}});
trackWebsiteEvent('page_view');
assert.equal(calls,0); assert.equal(local.getItem('althera_visitor_id'),null);
local.setItem(CONSENT_KEY,JSON.stringify(valid));
trackWebsiteEvent('page_view'); assert.equal(calls,1); assert.ok(local.getItem('althera_visitor_id'));
