trackWebsiteEvent('contact_intent'); assert.equal(calls,1); assert.equal(local.getItem('althera_visitor_id'),null); assert.equal(session.getItem('althera_session_id'),null);
local.setItem(CONSENT_KEY,JSON.stringify({...valid,expiresAt:now-1}));
trackWebsiteEvent('page_view'); assert.equal(calls,1);
