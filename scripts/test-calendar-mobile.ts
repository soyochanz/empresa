import assert from 'node:assert/strict';
import {localClock,eventVisible,validPushEndpoint} from '../api/calendar/digest';
import {hasService} from '../src/utils/serviceCatalog';
assert.deepEqual(localClock(new Date('2026-11-04T04:00:00Z'),'Asia/Dubai'),{date:'2026-11-04',minutes:480});
assert.equal(localClock(new Date('2026-07-04T06:00:00Z'),'Europe/Madrid').minutes,480);
assert.equal(localClock(new Date('2026-01-04T07:00:00Z'),'Europe/Madrid').minutes,480);
const e=(meta:string)=>({description:`Task\n\n---METADATA---\n${meta}`});
assert(eventVisible(e('status: pending'),'u','a@example.com'));
assert(!eventVisible(e('status: done'),'u','a@example.com'));
assert(!eventVisible(e('isPrivate: true'),'u','a@example.com'));
assert(!eventVisible(e('assignedUserEmail: b@example.com'),'u','a@example.com'));
assert(eventVisible(e('assignedUserEmails: a%40example.com,b%40example.com'),'u','a@example.com'));
assert(eventVisible(e('assignedUserEmail: todos-admins'),'u','a@example.com'));
assert(validPushEndpoint('https://web.push.apple.com/abc'));
assert(!validPushEndpoint('https://web.push.apple.com.attacker.com/abc'));
assert(!validPushEndpoint('https://localhost/abc'));
assert(!validPushEndpoint('https://web.push.apple.com:8443/abc'));
assert(hasService({status:'Client',requestedProducts:['SEO']} as any,'SEO'));
assert(!hasService({status:'Client',requestedProducts:['RRSS']} as any,'SEO'));
assert(!hasService({status:'Lead',requestedProducts:['SEO']} as any,'SEO'));
assert(!hasService({status:'Client',archived:true,requestedProducts:['SEO']} as any,'SEO'));
console.log('Calendar: timezone, DST, visibility, endpoint validation and service grouping passed.');
