import assert from 'node:assert/strict';
import {discountedForecastAmount} from '../src/utils/stripeDiscountForecast';
import {convertManualRecurrence} from '../src/utils/convertManualRecurrence';
import {buildPaymentSchedule} from '../src/utils/paymentSchedule';
const now=new Date('2026-11-18T12:00:00');
assert.equal(discountedForecastAmount(9.9,[{percent:100}],'2026-11-24'),0);
assert.equal(discountedForecastAmount(10,[{percent:50,end:Date.parse('2026-12-01')/1000}],'2026-12-24'),10);
assert.equal(discountedForecastAmount(10,[{amount:3}],'2026-12-24'),7);
assert.equal(discountedForecastAmount(10,[{percent:100,once:true}],'2026-12-24'),10);
const plan:any={id:'sub_test',amount:9.9,currency:'eur',status:'active',customerName:'test',interval:'month',intervalCount:1,nextPaymentAt:'2026-11-24T12:00:00Z',nextInvoiceAmount:0,discounts:[{percent:100}],paymentCount:0};
assert.ok(buildPaymentSchedule([], [plan],[],now).every(p=>p.amount===0&&p.recurring&&p.discountApplied));
const source:any={id:'manual_test',type:'income',amount:150,status:'paid',date:'2026-11-01',paidAt:'2026-11-01',paymentMethod:'transfer',description:'SEO'};
const next=convertManualRecurrence(source,'2026-11-30','3',now);
assert.equal(source.status,'paid');assert.notEqual(next.id,source.id);assert.equal(next.status,'pending');
assert.equal(buildPaymentSchedule([source,next],[],[],now).length,3);
assert.equal(convertManualRecurrence({...source,status:'pending'},'2026-11-30','',now).id,source.id);
assert.throws(()=>convertManualRecurrence({...source,paymentMethod:'stripe'},'2026-11-30','',now));
assert.throws(()=>convertManualRecurrence(source,'2026-11-30','0',now));
console.log('Discount expiry, zero forecasts, monthly limits, paid history and Stripe exclusion verified.');
