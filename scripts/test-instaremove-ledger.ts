import assert from 'node:assert/strict';
import type Stripe from 'stripe';
import { buildInstaremoveReceipt } from '../api/instaremoveLedger';
const subscription = { id: 'sub_demo', metadata: { app: 'instaremoveai' } } as unknown as Stripe.Subscription;
const invoice = { id: 'in_demo', status: 'paid', amount_paid: 1900, currency: 'eur', created: 1780000000, status_transitions: {}, customer_email: 'test@example.com', lines: { data: [{ description: 'Pro monthly' }] } } as unknown as Stripe.Invoice;
const stripe = {} as Stripe;
const receipt = await buildInstaremoveReceipt(stripe, invoice, subscription, '2026-05-29');
assert.equal(receipt?.amount, 19);
assert.equal(receipt?.category, 'InstaremoveAI');
assert.equal(receipt?.date, '2026-05-29');
assert.equal(receipt?.id, (await buildInstaremoveReceipt(stripe, invoice, subscription))?.id);
assert.match(receipt!.description, /STRIPEINVOICE:in_demo/);
assert.equal(await buildInstaremoveReceipt(stripe, { ...invoice, status: 'open' }, subscription), null);
assert.equal(await buildInstaremoveReceipt(stripe, { ...invoice, amount_paid: 0 }, subscription), null);
assert.equal(await buildInstaremoveReceipt(stripe, invoice, { ...subscription, metadata: {} }), null);
const foreignStripe = { invoicePayments: { list: () => ({ autoPagingToArray: async () => [{ amount_paid: 1900, payment: { payment_intent: { latest_charge: { balance_transaction: { currency: 'eur', exchange_rate: 0.92 } } } } }] }) } } as unknown as Stripe;
assert.equal((await buildInstaremoveReceipt(foreignStripe, { ...invoice, currency: 'usd' }, subscription))?.amount, 17.48);
await assert.rejects(buildInstaremoveReceipt(foreignStripe, { ...invoice, currency: 'usd', amount_paid: 2000 }, subscription), /conciliar/);
console.log('InstaremoveAI ledger checks passed');
